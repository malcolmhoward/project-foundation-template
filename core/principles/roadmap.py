"""
Roadmap Principle.

A roadmap communicates the project's direction and planned features,
helping contributors understand priorities and make informed decisions.

Introduced in v3.3.0.
"""

PRINCIPLE_ID = "roadmap"

PRINCIPLE = {
    "name": "Roadmap",
    "why": "Contributors and users need to understand the project's direction",
    "what": "Documentation of planned features, priorities, and timelines",
    "risk": "Without it, contributors work on low-priority features or duplicate planned work",
}

EDUCATION = """
📚 LEARNING: A roadmap aligns contributor efforts with project goals.

A roadmap serves multiple purposes:
- Communicates project direction to contributors
- Helps users plan their own work around upcoming features
- Reduces duplicate or conflicting contributions
- Provides transparency about project priorities

A good roadmap includes:
- Short-term goals (what's being worked on now)
- Medium-term plans (next few releases)
- Long-term vision (where the project is heading)
- Items explicitly marked as "not planned"

Roadmaps should be updated regularly and reference related issues
or milestones for tracking progress.
"""
