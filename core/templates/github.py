def generate_ci_workflow_content() -> str:
    """Generate a language-neutral GitHub Actions CI workflow.

    The check step fails until it is replaced: a CI run that passes without running any
    checks would tell reviewers the code was checked when it was not.
    """
    return """# Continuous Integration Workflow
# Generated by Project Foundation Template v""" + SCRIPT_VERSION + """
#
# WHAT: runs your project's checks on every push and pull request.
# WHY: a green check should mean the code was built and tested, so every step here
#      must fail when its check fails.
# HOW: replace the "Run checks" step with your project's commands. Until you do, it
#      fails on purpose and says so.

name: CI

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

permissions:
  contents: read

jobs:
  build:
    runs-on: ubuntu-latest

    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      # [REPLACE: Add your language's setup step, for example:]
      #
      # Node.js (needs a committed package-lock.json for `npm ci` and the cache):
      # - uses: actions/setup-node@v4
      #   with:
      #     node-version: 20
      #     cache: npm
      #
      # Python:
      # - uses: actions/setup-python@v5
      #   with:
      #     python-version: "3.12"

      # [REPLACE: Replace this step with your install, lint, test and build commands, for example:]
      #   Node.js: npm ci && npm run lint && npm test && npm run build
      #   Python:  pip install -r requirements.txt && python -m pytest
      # Do not add `continue-on-error: true` to a check: the run would then pass
      # even when the check fails.
      - name: Run checks
        run: |
          echo "::error::CI is not configured yet: replace the 'Run checks' step in .github/workflows/ci.yml with your project's commands (examples are in the comments above the step)."
          exit 1

# ---
# TEMPLATE NOTICE:
# This is a starting point. You must:
# 1. Add your language's setup step
# 2. Replace the "Run checks" step with your build and test commands
# 3. Add other jobs as needed (security scanning, deployment, etc.)
#
# Generated with Project Foundation Template
# https://github.com/malcolmhoward/project-foundation-template
"""


def generate_pr_validation_workflow_content() -> str:
    """Generate PR validation workflow for conventional commits."""
    return """# Pull Request Validation
# Validates PR title follows conventional commits format

name: PR Validation

on:
  pull_request:
    types: [opened, edited, synchronize]

jobs:
  validate-pr-title:
    runs-on: ubuntu-latest
    steps:
      - name: Validate PR title
        uses: amannn/action-semantic-pull-request@v5
        env:
          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        with:
          # Require conventional commit format
          types: |
            feat
            fix
            docs
            style
            refactor
            perf
            test
            build
            ci
            chore
            revert
          requireScope: false
          subjectPattern: ^.{1,50}$
          subjectPatternError: |
            PR title must be 50 characters or less.
            Current length: {length}

# ---
# This workflow ensures PR titles follow conventional commits format.
# This helps with automatic changelog generation and semantic versioning.
#
# Generated with Project Foundation Template
"""
